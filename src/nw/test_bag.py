from test_auth import *
def run2():
    res=[]
    def ok(c,m): res.append(bool(c)); print(('PASS ' if c else 'FAIL ')+m)
    with sync_playwright() as p:
        b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800},device_scale_factor=2)
        mock=Mock(); ctx.route(f'https://{HOST}/**',mock.handle)
        pg=ctx.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        pg.goto('file://'+S); pg.wait_for_timeout(300)
        ok(not pg.is_visible('#bagBtn'),'túi ẩn khi chưa đăng nhập')
        pg.click('#tReg'); pg.fill('#aName','bag_test'); pg.fill('#aPw','abcdef'); pg.fill('#aPw2','abcdef'); pg.click('#aGo'); pg.wait_for_timeout(800); pg.evaluate("delete G.loot['dp.tukhi'];G.cult.dpg=true;G.lootUI()")
        ok(pg.is_visible('#hMenu .mb:nth-child(1)'),'nút Túi (HUD) hiện sau đăng nhập')
        nz=pg.evaluate("(()=>{const c=document.querySelector('#bagBtn canvas');const d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let n=0;for(let i=3;i<d.length;i+=4)if(d[i]>0)n++;return n})()")
        ok(nz>600,f'icon túi gấm đã được vẽ ({nz} điểm ảnh)')
        pg.screenshot(path=S.replace('game.html','bag_icon.png'),clip={'x':0,'y':0,'width':200,'height':110})
        pg.evaluate("document.getElementById('bagBtn').click()"); pg.wait_for_timeout(500)
        ok(pg.is_visible('#bag') and pg.is_visible('#bagEmpty'),'mở túi: không gian trống')
        pg.screenshot(path=S.replace('game.html','bag_empty.png'))
        pg.evaluate("G.loot['Thủy Long Châu']=2;G.lootUI()"); pg.evaluate("TTBag.openTab('T')"); pg.wait_for_timeout(200)
        ok('4 / 120' in pg.inner_text('#bagCap'),'dung tích túi: 2 châu × 2 ô = 4 / 120')
        pg.evaluate("TTBag.openTab('T')"); pg.wait_for_timeout(400)
        ok(pg.locator('#bagStage .it').count()==1 and not pg.is_visible('#bagEmpty'),'tab Trong túi: 1 vật phẩm lơ lửng')
        pg.click('#bagStage .it',force=True); pg.wait_for_timeout(200)
        ok('Thủy Long Châu ×2' in pg.inner_text('#bagInfo') and 'Thủy' in pg.inner_text('#bagInfo'),'chạm vật phẩm → hiện tên + mô tả')
        ok(pg.inner_text('#bagBtn .cnt')=='1','huy hiệu trên túi hiện số loại')
        pg.screenshot(path=S.replace('game.html','bag_full.png'))
        pg.evaluate("TTBag.close()")
        ok(not pg.is_visible('#bag'),'đóng túi')
        pg.evaluate("window.__pause=false;G.keys.d=1"); pg.wait_for_timeout(2600); pg.evaluate("G.keys.d=0"); pg.wait_for_timeout(1200)
        pg.evaluate("TT.push(false,false)"); pg.wait_for_timeout(500)
        sv=list(mock.saves.values())[0]['data']
        ok(sv['loot'].get('Thủy Long Châu')==2 and sv['stats']['steps']>=5,f"đã lưu lên máy chủ: {sv['loot']} {sv['stats']}")
        pg.reload(); pg.wait_for_timeout(900)
        pg.evaluate("document.getElementById('bagBtn').click()"); pg.wait_for_timeout(400)
        ok(pg.locator('#bagStage .it').count()==1,'tải lại → vật phẩm vẫn lơ lửng trong túi')
        ok('tabJ' not in pg.content(),'đã bỏ tab Đạo Ký')
        ok(not errs,f'không lỗi JS {errs[:2]}')
        b.close()
    print('TỔNG',sum(res),'/',len(res)); sys.exit(0 if all(res) else 1)
run2()
